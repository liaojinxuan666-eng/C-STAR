#!/bin/sh
# Works with either the GitHub repository's examples/ layout or local tests/ layout.
set -eu
ROOT=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
cd "$ROOT"
if [ -f examples/ptr_test.cppo ]; then
    SRC=examples
elif [ -f tests/ptr_test.cppo ]; then
    SRC=tests
else
    echo 'ERROR: cannot find ptr_test.cppo in examples/ or tests/' >&2
    exit 1
fi
BIN="$ROOT/.cstar-test-bin"
mkdir -p "$BIN"

for name in comptime_if hello ptr_test sim_test comptime_ast type_system array_enum usize_test memory_types lowlevel atomic ffi_test ffi_host.c type_alias type_alias_host.c math.cppo math.cso module_v12 cast_invalid alignof_invalid abi_invalid array_invalid lvalue_invalid; do
    case "$name" in
        *.c) [ -f "$SRC/$name" ] || { echo "ERROR: missing $SRC/$name" >&2; exit 1; } ;;
        *.cso) : ;; # generated by --emit-module below
        *) [ -f "$SRC/$name" ] || [ -f "$SRC/$name.cppo" ] || { echo "ERROR: missing $SRC/$name.cppo" >&2; exit 1; } ;;
    esac
done
if [ -f "$SRC/simd128.cppo" ]; then
    SIMD_SRC="$SRC/simd128.cppo"
elif [ -f examples/simd128.cppo ]; then
    SIMD_SRC=examples/simd128.cppo
else
    echo 'ERROR: missing simd128.cppo in selected source directory or examples/' >&2
    exit 1
fi

clang -std=c11 -Wall -Wextra -Wpedantic src/cstar.c -o cstar

run_plain() {
    name=$1
    echo "== $name =="
    ./cstar "$SRC/$name.cppo"
    clang -std=c11 -Wall -Wextra -Wpedantic output.c -o "$BIN/$name"
    "$BIN/$name"
}

for name in comptime_if hello ptr_test sim_test comptime_ast type_system array_enum usize_test memory_types lowlevel atomic; do
    run_plain "$name"
done

echo '== ffi_test =='
./cstar "$SRC/ffi_test.cppo"
clang -std=c11 -Wall -Wextra -Wpedantic output.c "$SRC/ffi_host.c" -o "$BIN/ffi_test"
"$BIN/ffi_test"

echo '== type_alias =='
./cstar "$SRC/type_alias.cppo"
clang -std=c11 -Wall -Wextra -Wpedantic output.c "$SRC/type_alias_host.c" -o "$BIN/type_alias"
"$BIN/type_alias"

echo '== module_v12 =='
./cstar --emit-module "$SRC/math.cppo" "$SRC/math.cso"
./cstar "$SRC/module_v12.cppo"
clang -std=c11 -Wall -Wextra -Wpedantic output.c "$SRC/math.cso" -o "$BIN/module_v12"
"$BIN/module_v12"

echo '== simd128 =='
./cstar "$SIMD_SRC"
clang -std=c11 -O3 -Wall -Wextra -Wpedantic -Iinclude output.c runtime/cstar_simd128.c -o "$BIN/simd128"
"$BIN/simd128"

expect_reject() {
    name=$1
    expected=$2
    log="$BIN/$name.log"
    echo "== expected rejection: $name =="
    if ./cstar "$SRC/$name.cppo" >"$log" 2>&1; then
        echo "ERROR: $name was unexpectedly accepted"
        exit 1
    fi
    if ! grep -q "$expected" "$log"; then
        echo "ERROR: $name failed for an unexpected reason"
        cat "$log"
        exit 1
    fi
}

expect_reject cast_invalid 'invalid explicit cast'
expect_reject alignof_invalid 'unknown type in sizeof/alignof'
expect_reject abi_invalid 'C ABI argument type mismatch'
expect_reject array_invalid 'indexing requires an array or pointer'
expect_reject lvalue_invalid 'left side of assignment must be assignable'

echo
printf '%s\n' 'C* v0.16 regression suite: PASS'
